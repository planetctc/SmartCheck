const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('smartdisk', {
  scan: () => ipcRenderer.invoke('disks:scan'),
  version: () => ipcRenderer.invoke('app:version'),
  settings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (v) => ipcRenderer.invoke('settings:save', v),
  makeReport: (form) => ipcRenderer.invoke('report:make', form),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  startTask: (kind, disk, letter) => ipcRenderer.invoke('task:start', { kind, disk, letter }),
  cancelTask: () => ipcRenderer.invoke('task:cancel'),
  selfTest: (disk, what) => ipcRenderer.invoke('selftest', { disk, what }),
  taskResults: () => ipcRenderer.invoke('task:results'),
  monitorState: () => ipcRenderer.invoke('monitor:get'),
  history: () => ipcRenderer.invoke('history:get'),
  license: () => ipcRenderer.invoke('license:get'),
  setLicense: (key) => ipcRenderer.invoke('license:set', key),
  remoteTest: () => ipcRenderer.invoke('remote:test'),
  smartaccState: () => ipcRenderer.invoke('smartacc:state'),
  installSensors: () => ipcRenderer.invoke('sensors:install'),
  liveSensors: (on) => ipcRenderer.invoke('sensors:live', on),
  onLiveSensors: (fn) => ipcRenderer.on('sensors:live', (_e, list) => fn(list)),
  alertData: () => ipcRenderer.invoke('alert:get'),
  alertAction: (a) => ipcRenderer.invoke('alert:action', a),
  onAlert: (fn) => ipcRenderer.on('alert:data', (_e, d) => fn(d)),
  onTask: (fn) => ipcRenderer.on('task:event', (_e, ev) => fn(ev)),
  burnStart: (o) => ipcRenderer.invoke('burn:start', o),
  burnStop: () => ipcRenderer.invoke('burn:stop'),
  burnState: () => ipcRenderer.invoke('burn:state'),
  onBurn: (fn) => ipcRenderer.on('burn:event', (_e, ev) => fn(ev)),
  memStart: (o) => ipcRenderer.invoke('mem:start', o),
  memStop: () => ipcRenderer.invoke('mem:stop'),
  memState: () => ipcRenderer.invoke('mem:state'),
  memFull: () => ipcRenderer.invoke('mem:full'),
  onMem: (fn) => ipcRenderer.on('mem:event', (_e, ev) => fn(ev)),
  batteryRead: () => ipcRenderer.invoke('battery:read'),
  batteryHtml: () => ipcRenderer.invoke('battery:html'),
  onUpdate: (fn) => ipcRenderer.on('update:status', (_e, s) => fn(s)),
});
